import assert from 'node:assert/strict';
import {movement,freeCamera} from './free-camera.js';
import * as THREE from './vendor/three.module.js';
const move=(keys,yaw=0,pitch=0,dt=.02)=>movement(new Set(keys),yaw,pitch,dt);
assert.ok(move([]).every(v=>v===0));
assert.ok(move(['KeyW','KeyS','KeyA','KeyD','KeyQ','KeyE']).every(v=>v===0));
assert.ok(Math.abs(move(['KeyW'],Math.PI/2)[0]+.03)<1e-12);
assert.ok(move(['KeyW'],0,Math.PI/4)[1]>0);
assert.equal(move(['KeyE'])[1],.03);
assert.equal(move(['KeyQ'])[1],-.03);
assert.ok(Math.abs(Math.hypot(...move(['KeyW','KeyD','KeyE']))-.03)<1e-12);
assert.ok(Math.abs(move(['KeyW'],0,0,100)[2]+.075)<1e-12);
assert.ok(move(['KeyW'],0,0,-1)[2]===0);
console.log('Free camera: axes, cancellation, pitch, diagonal speed and pause limit passed');
globalThis.window=new EventTarget();
const canvas=new EventTarget();canvas.setAttribute=()=>{};canvas.focus=()=>{};canvas.setPointerCapture=()=>{};
const camera=new THREE.PerspectiveCamera(),controls={target:new THREE.Vector3(),enabled:true};
const flight=freeCamera(THREE,camera,controls,canvas,()=>{});
const send=(name,properties={})=>{const event=new Event(name,{cancelable:true});Object.assign(event,properties);canvas.dispatchEvent(event)};
flight.set(true);assert.equal(controls.enabled,false);
send('keydown',{code:'KeyW'});flight.update(.02);assert.ok(camera.position.z<0);
send('blur');const stopped=camera.position.clone();flight.update(.02);assert.ok(camera.position.equals(stopped));
send('pointerdown',{button:2,pointerId:1,clientX:100,clientY:100});
send('pointermove',{pointerId:1,clientX:200,clientY:50});
const direction=camera.getWorldDirection(new THREE.Vector3());assert.ok(direction.x>0&&direction.y>0);
send('pointermove',{pointerId:1,clientX:200,clientY:-100000});assert.ok(Number.isFinite(camera.quaternion.x));
send('pointerup',{pointerId:1});send('keydown',{code:'Escape'});
assert.equal(flight.active,false);assert.equal(controls.enabled,true);assert.ok(Math.abs(controls.target.distanceTo(camera.position)-2)<1e-12);
console.log('Free camera input: right-drag look, focus loss, pitch clamp and Escape return passed');
